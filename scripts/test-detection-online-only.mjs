import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { load, dom, root } from "./lib/web-ui-harness.mjs";
const require = createRequire(`${root}/package.json`);
const { onlineManager, QueryClient, MutationObserver } = require("@tanstack/react-query");
const { requireDetectionOnline } = await import(load("src/modules/notifications/lib/detection-online.ts"));
const { savePreparedDetection } = await import(load("src/modules/notifications/lib/detection-quick-save.ts"));
let calls = 0; const client = new QueryClient({ defaultOptions: { mutations: { retry: false } } });
const mutation = new MutationObserver(client, { networkMode: "always", mutationFn: async () => { requireDetectionOnline(); calls++; } });
onlineManager.setOnline(false);
await assert.rejects(mutation.mutate(), /Necesitas conexión/);
assert.equal(mutation.getCurrentResult().isPaused, false);
const suggestion = { id: 1 }, input = { userId: "u", workspaceId: 1 };
await assert.rejects(() => savePreparedDetection(suggestion, input, [], [], [], { store: { register: async () => { calls++; } }, checker: {}, create: async () => 1, signal: new AbortController().signal, proAccessEnabled: false }), /Necesitas conexión/);
assert.equal(calls, 0); onlineManager.setOnline(true); await new Promise(resolve => setTimeout(resolve, 20)); assert.equal(calls, 0, "a rejected detection must not execute on reconnect");
Object.defineProperty(globalThis, "navigator", { configurable: true, value: { onLine: false } });
assert.throws(() => requireDetectionOnline(), /Necesitas conexión/, "initial offline must not depend on an event");
delete globalThis.navigator;
client.clear(); dom.window.close(); console.log("Detection offline: immediate error and no replay after reconnection passed.");
